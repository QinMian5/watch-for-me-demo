"""Insert the source attribution line at the top of media.html.

media.html is regenerated by Watch for Me's render command, which does not
carry license information. Run this script after every render:

    python3 add_attribution.py
"""

from pathlib import Path

PAGE = Path(__file__).with_name("media.html")
MARK = '<div id="attribution"'
BLOCK = (
    "<style>#attribution{font-size:13px;line-height:1.6;padding:8px 16px;"
    "color:var(--muted);background:var(--bg);border-bottom:1px solid var(--line)}"
    "#attribution a{color:var(--accent)}</style>"
    '<div id="attribution">示例素材：'
    '<a href="https://www.youtube.com/watch?v=k-bfLnR0VGo">'
    "Agentics Day: MCP + Agents: MCP in 2026: Context is All You Need</a>，"
    "作者 David Soria Parra（Anthropic），由 CNCF [Cloud Native Computing Foundation] 发布，"
    '采用 <a href="https://creativecommons.org/licenses/by/4.0/">CC BY 4.0</a> 许可。'
    '本页由 <a href="https://github.com/QinMian5/watch-for-me">Watch for Me</a> 生成，'
    "对原视频做了转写、翻译和整理。</div>"
)

html = PAGE.read_text(encoding="utf-8")
if MARK not in html:
    anchor = '<div id="app"'
    if html.count(anchor) != 1:
        raise SystemExit("media.html: expected exactly one #app element")
    PAGE.write_text(html.replace(anchor, BLOCK + anchor), encoding="utf-8")
print("attribution present")
